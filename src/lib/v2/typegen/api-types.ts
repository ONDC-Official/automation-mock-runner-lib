import { schemaToTypeScript, wrapInNamespace } from "./compile";
import {
	fnv1a,
	getRequestSchemas,
	getSpecLabel,
	type JsonSchemaV2,
	type SpecDocumentV2,
} from "./spec";

/** @experimental */
export interface ApiTypesV2 {
	/** Global (script-mode) declarations: `OndcApi.Payloads`, `Payload<A>`, … */
	dts: string;
	/** The APIs typed, sorted: `search`, `on_search`, … */
	apis: string[];
	/** Fingerprint of the schemas the types came from. */
	specHash: string;
	/** Paths that were skipped, e.g. no JSON request body. */
	warnings: string[];
}

/**
 * The global helpers every typed step file uses. `Payload<A>` falls back to a
 * loose payload for an API the spec doesn't define (forms, custom APIs), so a
 * typed template always compiles.
 */
const PAYLOAD_HELPERS = `/** An API the spec defines a request body for. */
type ApiName = keyof OndcApi.Payloads;

/** Any ONDC payload: what an API without a schema gets. */
type AnyPayload = { context: any; message: any; [key: string]: any };

/** The request payload of \`A\`, from the spec's JSON Schema. */
type Payload<A extends string> = A extends ApiName ? OndcApi.Payloads[A] : AnyPayload;`;

/**
 * What the editor declares when there is no spec to type from: every payload
 * is \`AnyPayload\`, so typed templates still compile.
 *
 * @experimental
 */
export const API_TYPES_FALLBACK_DTS_V2 = `// No spec types available: every payload is AnyPayload.
declare namespace OndcApi {
    export interface Payloads {}
}
${PAYLOAD_HELPERS}
`;

/**
 * The request schemas plus what their `$ref`s point into, as one JSON Schema
 * whose root has a property per API. Responses are dropped: they are ACKs the
 * step code never sees, and some of their `$ref`s point at other responses.
 */
export const buildPayloadsSchema = (spec: SpecDocumentV2) => {
	const requests = getRequestSchemas(spec);
	const properties: Record<string, JsonSchemaV2> = {};
	const paths: Record<string, unknown> = {};
	for (const { api, schema } of requests) {
		properties[api] = schema;
		paths[`/${api}`] = {
			post: { requestBody: { content: { "application/json": { schema } } } },
		};
	}
	return {
		root: {
			title: "Payloads",
			description: "Request payload of each API, keyed by API name.",
			type: "object",
			properties,
			required: Object.keys(properties),
			additionalProperties: false,
			components: spec.components ?? {},
			paths,
		},
		apis: requests.map((request) => request.api),
	};
};

/**
 * TypeScript declarations for every API in a spec, generated from the request
 * body JSON Schemas (`paths["/<api>"].post.requestBody`). Deterministic: the
 * same spec always gives byte-identical output.
 *
 * The result is a script (no import / export), for an editor's extra libs:
 *
 * ```ts
 * async function generate(defaultPayload: Payload<"search">, sessionData: SessionData): Promise<Payload<"search">>
 * ```
 *
 * @experimental
 */
export const generateApiTypesV2 = async (
	spec: SpecDocumentV2,
): Promise<ApiTypesV2> => {
	const { root, apis } = buildPayloadsSchema(spec);
	const warnings = Object.keys(spec.paths ?? {})
		.filter((path) => !apis.includes(path.slice(1)))
		.map((path) => `${path}: no JSON request body schema; typed as AnyPayload`);
	const specHash = fnv1a(
		JSON.stringify({ paths: root.paths, components: root.components }),
	);
	const { domain, version } = getSpecLabel(spec);

	const declarations =
		apis.length > 0 ? await schemaToTypeScript(root, "Payloads") : "";
	const body = declarations || "export interface Payloads {}";

	const dts = [
		"// Generated by @ondc/automation-mock-runner generateApiTypesV2. Do not edit.",
		`// ${[domain, version].filter(Boolean).join(" ") || "spec"} · ${apis.length} APIs · spec ${specHash}`,
		wrapInNamespace("OndcApi", body),
		"",
		PAYLOAD_HELPERS,
		"",
	].join("\n");

	return { dts, apis, specHash, warnings };
};
