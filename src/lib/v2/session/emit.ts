import { buildPayloadsSchema } from "../typegen/api-types";
import { schemaToTypeScript, wrapInNamespace } from "../typegen/compile";
import { resolveJsonPathSchemaV2 } from "../typegen/jsonpath-schema";
import {
	derefPointer,
	type JsonSchemaV2,
	type SpecDocumentV2,
} from "../typegen/spec";
import type { SessionDataSchemaV2, SessionKeyV2 } from "./schema";

/** @experimental */
export interface SessionTypesV2 {
	/** Global declarations: `OndcSession.Stored`, `OndcSession.View`, `SessionDataRaw`, `SessionData`. */
	dts: string;
	schemaId: string;
}

/**
 * What the editor declares without a session schema: any key, any value.
 *
 * @experimental
 */
export const SESSION_TYPES_FALLBACK_DTS_V2 = `// No session schema: sessionData is untyped.
type SessionDataRaw = Record<string, any>;
type SessionData = Record<string, any>;
`;

/**
 * The JSON Schema of one match of a key: its `schema` override, or the union
 * of the schemas its sources' JSONPaths land on (`any` where one doesn't resolve).
 */
const getMatchSchema = (
	key: SessionKeyV2,
	spec: SpecDocumentV2,
): JsonSchemaV2 => {
	if (key.schema !== undefined) return key.schema;
	const members: Array<Record<string, any>> = [];
	for (const source of key.sources ?? []) {
		if (source.eval || !source.api) {
			members.push({});
			continue;
		}
		const { pointers } = resolveJsonPathSchemaV2(spec, source.api, source.path);
		if (pointers.length === 0) members.push({});
		pointers.forEach((pointer) => members.push({ $ref: pointer }));
	}
	// Specs inferred from examples repeat the same inline schema in every API
	// (TRV10's `context` 22 times): one member per distinct schema, not per path.
	const unique = [
		...new Map(
			members.map((m) => [
				JSON.stringify(
					typeof m.$ref === "string" ? derefPointer(spec, m.$ref) : m,
				),
				m,
			]),
		).values(),
	];
	if (unique.length === 0) return {};
	// `any` absorbs the rest of a union; say so rather than emit `any | Order`.
	if (unique.some((m) => JSON.stringify(m) === "{}")) return {};
	return unique.length === 1 ? unique[0] : { anyOf: unique };
};

const describe = (key: SessionKeyV2) =>
	[
		key.description,
		...(key.sources ?? []).map(
			(source) =>
				`${source.append ? "Appended" : "Saved"} by ${source.action ?? source.api ?? "a step"}: ${
					source.eval ? "EVAL# extractor" : source.path
				}`,
		),
	]
		.filter(Boolean)
		.join("\n");

/**
 * Types for `sessionData`, from a session-data schema:
 *
 * - `SessionDataRaw`: as stored, every JSONPath key a list of matches
 *   (`city_code: string[]`). What v1-style code (`sessionData.city_code[0]`) reads.
 * - `SessionData`: the V2 view, where `cardinality: one` keys are unwrapped
 *   (`city_code: string`); see `buildSessionViewV2`.
 *
 * Every key is optional: what exists depends on how far the flow has run.
 * Unless `meta.closed`, undeclared keys are allowed (`[key: string]: any`).
 *
 * @experimental
 */
export const generateSessionTypesV2 = async (
	schema: SessionDataSchemaV2,
	spec: SpecDocumentV2,
): Promise<SessionTypesV2> => {
	const stored: Record<string, JsonSchemaV2> = {};
	const view: Record<string, JsonSchemaV2> = {};
	for (const [name, key] of Object.entries(schema.keys)) {
		const match = getMatchSchema(key, spec);
		const description = describe(key) || undefined;
		const isList =
			!key.builtin && !(key.sources ?? []).every((source) => source.eval);
		const storedSchema = isList ? { type: "array", items: match } : match;
		const viewSchema =
			isList && key.cardinality === "one" ? match : storedSchema;
		stored[name] = withDescription(storedSchema, description);
		view[name] = withDescription(viewSchema, description);
	}

	const { root: payloads } = buildPayloadsSchema(spec);
	const open = schema.meta.closed !== true;
	const root = {
		title: "Session",
		type: "object",
		properties: {
			stored: {
				title: "Stored",
				type: "object",
				properties: stored,
				additionalProperties: open,
			},
			view: {
				title: "View",
				type: "object",
				properties: view,
				additionalProperties: open,
			},
		},
		required: ["stored", "view"],
		additionalProperties: false,
		components: payloads.components,
		paths: payloads.paths,
	};

	const declarations = await schemaToTypeScript(root, "Session");
	const label = [schema.meta.domain, schema.meta.version, schema.meta.usecase]
		.filter(Boolean)
		.join(" ");
	const dts = [
		"// Generated by @ondc/automation-mock-runner generateSessionTypesV2. Do not edit.",
		`// Session schema ${schema.id}${label ? ` · ${label}` : ""}`,
		wrapInNamespace("OndcSession", declarations),
		"",
		"/** Session data as stored: each saved JSONPath is a list of matches. */",
		"type SessionDataRaw = OndcSession.Stored;",
		"/** Session data as V2 code sees it: `cardinality: one` keys unwrapped. */",
		"type SessionData = OndcSession.View;",
		"",
	].join("\n");

	return { dts, schemaId: schema.id };
};

/**
 * Adds a description (the JSDoc on the key). A `$ref` is wrapped rather than
 * given a sibling: dereferencing may drop the sibling or copy it onto the
 * shared target.
 */
const withDescription = (
	schema: JsonSchemaV2,
	description?: string,
): JsonSchemaV2 => {
	if (!description) return schema;
	if (typeof schema === "boolean") return schema ? { description } : schema;
	return typeof schema.$ref === "string"
		? { allOf: [schema], description }
		: { ...schema, description };
};
